#[test]
fn centered10_postrounding_negative_and_tie_vectors() {
    // A single v^10 coefficient C10=q10*2^140 has centered highest
    // coefficient q10. Each lower coefficient is rounded independently.
    const BINOM: [i128; 11] = [1, 10, 45, 120, 210, 252, 210, 120, 45, 10, 1];
    for q10 in [
        -8388608i64,
        -16384,
        -128,
        -1,
        0,
        1,
        128,
        16384,
        8388608,
        (1i64 << 40) - 1,
        -((1i64 << 40) - 1),
    ] {
        let mut full = [[0u64; 3]; 35];
        full[24] = [0, 0, (q10 as u64).wrapping_mul(4096)];
        let mut actual = [0i64; 12];
        unsafe {
            pretzel55_interval_center10_from_full(actual.as_mut_ptr(), full.as_ptr().cast());
        }
        assert_eq!(actual[0], 0);
        for j in 0..11usize {
            let power = (10 - j) as u32;
            let denominator = 8i128.pow(power);
            let numerator = q10 as i128 * BINOM[j] * 7i128.pow(power);
            let expected = (numerator + denominator / 2).div_euclid(denominator) as i64;
            assert_eq!(actual[11 - j], expected);
        }
    }
}
